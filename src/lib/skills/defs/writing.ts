/** A long method split into files under the size limit, named name.md, name-2.md, ... */
function parts(name: string, text: string): Record<string, string> {
  const out: Record<string, string> = {};
  const max = MAX_FILE_CHARS - 500;
  let rest = text.trim();
  for (let n = 1; rest; n++) {
    let cut = rest.length <= max ? rest.length : rest.lastIndexOf("\n\n", max);
    if (cut < max / 2) cut = max;
    out[n === 1 ? `${name}.md` : `${name}-${n}.md`] = rest.slice(0, cut).trim();
    rest = rest.slice(cut).trim();
  }
  return out;
}

